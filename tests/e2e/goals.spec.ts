const contributeTo = async (page: Page, name: string) => {
  await card(page, name).getByRole('button', { name: 'Contribute' }).click()
  const dialog = page.getByRole('dialog', { name: `Contribute to ${name}` })
  await expect(dialog.getByRole('button', { name: 'Close', exact: true })).toBeFocused()
  await expect(dialog.getByLabel('Amount')).toBeEnabled()
  return dialog
}

const latestTransfer = (page: Page) =>
  page.getByRole('region', { name: 'Transfers between accounts' }).getByRole('listitem').first()

test('creates a goal with a deadline, edits it and deletes it', async ({ page, isMobile }) => {
  const now = new Date()
  const year = now.getFullYear() + 1
  const months = year * 12 + 6 - (now.getFullYear() * 12 + now.getMonth() + 1)
  const monthly = (Math.ceil(120_000 / months) / 100).toLocaleString('en-US', { minimumFractionDigits: 2 })
  await page.goto('/goals')
  await expect(cards(page)).toHaveCount(3)
  await page.getByRole('button', { name: 'New goal' }).first().click()
  const dialog = page.getByRole('dialog', { name: 'New goal' })
  await expect(dialog.getByRole('button', { name: 'Close', exact: true })).toBeFocused()
  await dialog.getByRole('button', { name: 'Save' }).click()
  await expect(dialog.getByText('This field is required.')).toHaveCount(2)
  const name = dialog.getByLabel('Name', { exact: true })
  await expect(name).toBeFocused()
  await name.fill('Rower')
  await dialog.getByLabel('Target amount').pressSequentially('1200')
  await dialog.getByLabel('Deadline', { exact: true }).fill(`06/${year}`)
  const picker = page.getByRole('dialog', { name: 'Choose date' })
  await picker.locator('[data-pc-section="month"]', { hasText: 'Jun' }).click()
  await expect(picker).toBeHidden()
  await expect(dialog.getByLabel('Deadline', { exact: true })).toHaveValue(`06/${year}`)
  await dialog.getByRole('button', { name: 'Save' }).click()
  await expect(page.getByText('Goal created')).toBeVisible()
  const bike = card(page, 'Rower')
  await expect(bike).toContainText('0%')
  await expect(bike).toContainText(`Deadline: June ${year}`)
  if (!isMobile) await expect(bike).toContainText(`Save PLN ${monthly} a month to make it on time`)

  await bike.getByRole('button', { name: 'Edit Rower' }).click()
  const edit = page.getByRole('dialog', { name: 'Edit goal' })
  const editName = edit.getByLabel('Name', { exact: true })
  await expect(editName).toHaveValue('Rower')
  await expect(edit.getByRole('button', { name: 'Close', exact: true })).toBeFocused()
  await editName.fill('Rower górski')
  const target = edit.getByLabel('Target amount')
  await target.fill('')
  await target.pressSequentially('1500')
  await edit.getByRole('button', { name: 'Save' }).click()
  await expect(page.getByText('Goal updated')).toBeVisible()
  const renamed = card(page, 'Rower górski')
  await expect(renamed).toContainText('PLN 1,500.00')

  await renamed.getByRole('button', { name: 'Edit Rower górski' }).click()
  await edit.getByRole('button', { name: 'Delete' }).click()
  const confirm = page.getByRole('alertdialog')
  await expect(confirm).toContainText('Rower górski')
  await confirm.getByRole('button', { name: 'Delete' }).click()
  await expect(page.getByText('Goal deleted')).toBeVisible()
  await expect(cards(page)).toHaveCount(3)
  const focused = page.locator(':focus')
  await expect(focused).toHaveAccessibleName('New goal')
  await expect(focused).toBeVisible()
})

test('a contribution to a linked goal becomes a transfer into its savings account', async ({ page }) => {
  await page.goto('/goals')
  const dialog = await contributeTo(page, 'Fundusz awaryjny')
  await expect(dialog).toContainText('This creates a transfer from Konto główne to Oszczędności.')
  await dialog.getByRole('button', { name: 'Save' }).click()
  await expect(dialog.getByText('This field is required.')).toBeVisible()
  await expect(dialog.getByLabel('Amount')).toBeFocused()
  await dialog.getByLabel('Amount').pressSequentially('500')
  await dialog.getByRole('button', { name: 'Save' }).click()
  await expect(page.getByText('Contribution saved')).toBeVisible()
  await expect(card(page, 'Fundusz awaryjny')).toContainText('PLN 6,700.00')
  await page.goto('/accounts')
  await expect(card(page, 'Oszczędności')).toContainText('PLN 14,500.00')
  await expect(latestTransfer(page)).toContainText('Konto główne → Oszczędności')
  await expect(latestTransfer(page)).toContainText('PLN 500.00')
})

test('a cross-currency contribution uses the corrected exchange rate', async ({ page }) => {
  await page.goto('/goals')
  const dialog = await contributeTo(page, 'Fundusz awaryjny')
  await dialog.getByRole('combobox', { name: 'From account' }).click()
  await page.getByRole('option', { name: 'Konto EUR · EUR' }).click()
  const rate = dialog.getByLabel('Exchange rate (EUR → PLN)')
  await expect(rate).toHaveValue(/^4\.\d+$/)
  await rate.fill('')
  await rate.pressSequentially('4')
  await dialog.getByLabel('Amount').pressSequentially('100')
  await expect(dialog.getByText('Receives PLN 400.00')).toBeVisible()
  await dialog.getByRole('button', { name: 'Save' }).click()
  await expect(page.getByText('Contribution saved')).toBeVisible()
  await expect(card(page, 'Fundusz awaryjny')).toContainText('PLN 6,600.00')
})

test('a contribution to an unlinked goal only grows the goal', async ({ page }) => {
  await page.goto('/goals')
  const dialog = await contributeTo(page, 'Wakacje')
  await expect(dialog).toContainText('The amount is added to the goal; account balances do not change.')
  await dialog.getByLabel('Amount').pressSequentially('300')
  await dialog.getByRole('button', { name: 'Save' }).click()
  await expect(page.getByText('Contribution saved')).toBeVisible()
  await expect(card(page, 'Wakacje')).toContainText('PLN 4,500.00')
  await expect(card(page, 'Wakacje')).toContainText('56%')
  await page.goto('/accounts')
  await expect(latestTransfer(page)).toContainText('PLN 1,000.00')
})

test('reaching the target marks the goal as reached', async ({ page, isMobile }) => {
  await page.goto('/goals')
  const dialog = await contributeTo(page, 'Nowy laptop')
  await dialog.getByLabel('Amount').pressSequentially('1100')
  await dialog.getByRole('button', { name: 'Save' }).click()
  await expect(page.getByText('Contribution saved')).toBeVisible()
  const laptop = card(page, 'Nowy laptop')
  await expect(laptop).toContainText('Reached')
  await expect(laptop).toContainText('100%')
  if (!isMobile) {
    await expect(laptop).toContainText('Goal reached. Well done!')
    await expect(page.getByRole('region', { name: 'Goals summary' })).toContainText('PLN 15,400.00')
  }
})
