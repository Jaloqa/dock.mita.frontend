import { expect, type Page, test } from '@playwright/test'

test.skip(({ isMobile }) => isMobile, 'the sidebar button exists on desktop only')

const card = (page: Page, name: string) =>
  page.getByRole('article').filter({ has: page.getByRole('heading', { name, exact: true }) })

const openDialog = async (page: Page) => {
  await page.getByRole('button', { name: 'New transaction' }).click()
  const dialog = page.getByRole('dialog', { name: 'New transaction' })
  await expect(dialog.getByRole('button', { name: 'Close', exact: true })).toBeFocused()
  return dialog
}

test('a EUR expense from a PLN card lowers the card balance by the converted amount', async ({ page }) => {
  await page.goto('/accounts')
  await expect(card(page, 'Konto główne')).toContainText('zł 8,820.40')
  const dialog = await openDialog(page)
  await expect(dialog.getByRole('combobox', { name: 'Account' })).toContainText('Konto główne · PLN')
  await dialog.getByLabel('Amount').pressSequentially('50')
  await dialog.getByRole('combobox', { name: 'Currency' }).click()
  await page.getByRole('option', { name: 'EUR — Euro', exact: true }).click()
  const rate = dialog.getByLabel('Exchange rate (EUR → PLN)')
  await expect(rate).toHaveValue(/^4\.\d+$/)
  await expect(dialog.getByText('How many PLN equal 1 EUR on the selected date.')).toBeVisible()
  await rate.fill('')
  await rate.pressSequentially('4')
  await expect(dialog.getByText('On the account: zł 200.00')).toBeVisible()
  await dialog.getByLabel('Description').fill('Książki')
  await dialog.getByRole('button', { name: 'Save' }).click()
  await expect(dialog).toBeHidden()
  await expect(page.getByText('Transaction saved')).toBeVisible()
  await expect(card(page, 'Konto główne')).toContainText('zł 8,620.40')
})

test('editing a EUR expense keeps its custom exchange rate', async ({ page }) => {
  await page.goto('/transactions')
  await page.getByRole('button', { name: 'Add transaction' }).click()
  const dialog = page.getByRole('dialog', { name: 'New transaction' })
  await expect(dialog.getByRole('button', { name: 'Close', exact: true })).toBeFocused()
  await dialog.getByLabel('Amount').pressSequentially('50')
  await dialog.getByRole('combobox', { name: 'Currency' }).click()
  await page.getByRole('option', { name: 'EUR — Euro', exact: true }).click()
  const rate = dialog.getByLabel('Exchange rate (EUR → PLN)')
  await expect(rate).toHaveValue(/^4\.\d+$/)
  await rate.fill('')
  await rate.pressSequentially('4')
  await expect(dialog.getByText('On the account: zł 200.00')).toBeVisible()
  await dialog.getByLabel('Description').fill('Antykwariat')
  await dialog.getByRole('button', { name: 'Save' }).click()
  await expect(dialog).toBeHidden()
  await expect(page.getByText('Transaction saved')).toBeVisible()
  await page.getByRole('region', { name: 'Filters' }).getByRole('searchbox', { name: 'Search' }).fill('Antykwariat')
  const rows = page.getByRole('region', { name: 'Transactions' }).locator('tbody tr')
  await expect(rows.first()).toContainText('Antykwariat')
  await expect(rows).toHaveCount(1)
  await rows.first().getByRole('button', { name: 'Antykwariat' }).click()
  const edit = page.getByRole('dialog', { name: 'Edit transaction' })
  await expect(edit.getByRole('combobox', { name: 'Currency' })).toContainText('EUR')
  const editRate = edit.getByLabel('Exchange rate (EUR → PLN)')
  await expect(editRate).toHaveValue('4.00')
  await expect(edit.getByText('On the account: zł 200.00')).toBeVisible()
  await expect(edit.getByRole('button', { name: 'Close', exact: true })).toBeFocused()
  await edit.getByLabel('Note').fill('Stare wydanie')
  await edit.getByRole('button', { name: 'Save' }).click()
  await expect(edit).toBeHidden()
  await expect(page.getByText('Transaction updated')).toBeVisible()
  await expect(rows.first()).toContainText('Stare wydanie')
  await rows.first().getByRole('button', { name: 'Antykwariat' }).click()
  await expect(editRate).toHaveValue('4.00')
  await expect(edit.getByLabel('Note')).toHaveValue('Stare wydanie')
})

test('validates the amount before saving and focuses it', async ({ page }) => {
  await page.goto('/accounts')
  const dialog = await openDialog(page)
  await dialog.getByRole('button', { name: 'Save' }).click()
  await expect(dialog.getByText('This field is required.')).toBeVisible()
  await expect(dialog.getByLabel('Amount')).toBeFocused()
})

test('the closed category select shows the colour of the chosen category', async ({ page }) => {
  await page.goto('/accounts')
  const dialog = await openDialog(page)
  const category = dialog.getByRole('combobox', { name: 'Category' })
  await expect(category).toContainText('Spożywcze')
  await expect(category.locator('.bg-chart-2')).toBeVisible()
  await category.click()
  await page.getByRole('listbox').getByRole('option', { name: 'Mieszkanie' }).click()
  await expect(category).toHaveAttribute('aria-expanded', 'false')
  await expect(category).toContainText('Mieszkanie')
  await expect(category.locator('.bg-chart-1')).toBeVisible()
})

test('income offers income categories only', async ({ page }) => {
  await page.goto('/accounts')
  const dialog = await openDialog(page)
  const category = dialog.getByRole('combobox', { name: 'Category' })
  await expect(category).toContainText('Spożywcze')
  await dialog.getByRole('button', { name: 'Income', exact: true }).click()
  await expect(category).toContainText('Wynagrodzenie')
  await category.click()
  await expect(page.getByRole('option', { name: 'Premia' })).toBeVisible()
  await expect(page.getByRole('option', { name: 'Spożywcze' })).toHaveCount(0)
  await expect(page.getByRole('option', { name: 'Przelewy' })).toHaveCount(0)
})
