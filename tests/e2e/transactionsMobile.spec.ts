import { expect, type Page, test } from '@playwright/test'
import { overlayOption, pickOverlayOption } from './overlayOption'

test.skip(({ isMobile }) => !isMobile, 'cards grouped by day are the mobile layout')

const list = (page: Page) => page.getByRole('region', { name: 'Transactions by day' })

const showAllTime = async (page: Page) => {
  await page.getByRole('button', { name: 'Filters' }).click()
  const drawer = page.getByRole('dialog', { name: 'Filters' })
  await drawer.getByRole('combobox', { name: 'Period' }).click()
  await page.getByRole('option', { name: 'All time' }).click()
  await drawer.getByRole('button', { name: 'Show results' }).click()
  await expect(drawer).toBeHidden()
}

test('groups transactions by day and filters them with chips, search and a drawer', async ({ page }) => {
  await page.goto('/transactions')
  await expect(page.getByRole('heading', { level: 1, name: 'Transactions' })).toBeVisible()
  await showAllTime(page)
  await expect(list(page).getByRole('heading').first()).toBeVisible()
  await expect(page.getByRole('region', { name: 'Filter summary' })).toContainText(/Found: \d+ transactions/)
  await page.getByRole('button', { name: 'Income', exact: true }).click()
  await expect(list(page).getByRole('listitem').filter({ hasText: 'Wynagrodzenie' }).first()).toBeVisible()
  await expect(list(page).getByRole('listitem').filter({ hasText: 'Czynsz' })).toHaveCount(0)
  await page.getByRole('searchbox', { name: 'Search' }).fill('Odsetki')
  await expect(list(page).getByRole('listitem').first()).toContainText('Odsetki')
  await expect(list(page).getByRole('listitem').filter({ hasNotText: 'Odsetki' })).toHaveCount(0)
})

test('opens the edit dialog from a card', async ({ page }) => {
  await page.goto('/transactions')
  await showAllTime(page)
  await page.getByRole('searchbox', { name: 'Search' }).fill('Czynsz')
  await expect(list(page).getByRole('listitem').first()).toContainText('Czynsz')
  await expect(list(page).getByRole('listitem').filter({ hasNotText: 'Czynsz' })).toHaveCount(0)
  await list(page).getByRole('listitem').first().getByRole('button').click()
  const dialog = page.getByRole('dialog', { name: 'Edit transaction' })
  await expect(dialog.getByLabel('Description')).toHaveValue('Czynsz')
  await dialog.getByRole('button', { name: 'Cancel' }).click()
  await expect(dialog).toBeHidden()
})

test('resets the filters from the drawer', async ({ page }) => {
  await page.goto('/transactions')
  await showAllTime(page)
  await page.getByRole('button', { name: 'Filters' }).click()
  const drawer = page.getByRole('dialog', { name: 'Filters' })
  await drawer.getByRole('button', { name: 'Reset filters' }).click()
  await expect(drawer.getByRole('combobox', { name: 'Period' })).toContainText('This month')
})

test('adds an expense on the full-screen keypad', async ({ page }) => {
  await page.goto('/transactions')
  await expect(page.getByRole('heading', { level: 1, name: 'Transactions' })).toBeVisible()
  await page.getByRole('link', { name: 'New transaction' }).click()
  await expect(page).toHaveURL('/transactions/new')
  await page.getByRole('button', { name: 'Save' }).click()
  await expect(page.getByText('Enter an amount above zero.')).toBeVisible()
  const keypad = page.getByRole('group', { name: 'Keypad' })
  for (const key of ['4', '2', 'Decimal separator', '5']) {
    await keypad.getByRole('button', { name: key, exact: true }).click()
  }
  await expect(page.getByLabel('Amount')).toHaveText(/^−zł\s42\.5$/)
  await page.getByRole('button', { name: 'Kawiarnie' }).click()
  await expect(page.getByRole('button', { name: 'Kawiarnie' })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Save' }).click()
  await expect(page).toHaveURL('/transactions')
  await expect(page.getByText('Transaction saved')).toBeVisible()
  const added = list(page).getByRole('listitem').filter({ hasText: '-zł 42.50' }).first()
  await expect(added).toContainText('Kawiarnie')
})

test('switches to income and picks the account and the date in drawers', async ({ page }) => {
  await page.goto('/transactions/new')
  await page.getByRole('button', { name: 'Income', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Wynagrodzenie' })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('button', { name: 'Spożywcze' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Account: Konto główne' }).click()
  await page
    .getByRole('dialog', { name: 'Choose an account' })
    .getByRole('button', { name: /Oszczędności/ })
    .click()
  await expect(page.getByRole('button', { name: 'Account: Oszczędności' })).toBeVisible()
  await page.getByRole('button', { name: 'Date: Today' }).click()
  await expect(page.getByRole('dialog', { name: 'Choose a date' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog', { name: 'Choose a date' })).toBeHidden()
  await page.keyboard.type('7')
  await expect(page.getByLabel('Amount')).toHaveText(/^\+zł\s7$/)
  await page.getByRole('button', { name: 'Close' }).click()
  await expect(page).not.toHaveURL(/\/transactions\/new$/)
})

test('edits the amount with physical digits, comma, dot and Backspace', async ({ page }) => {
  await page.goto('/transactions/new')
  const amount = page.getByLabel('Amount')
  await expect(amount).toHaveText(/^−zł\s0$/)
  await page.keyboard.type('42,5')
  await expect(amount).toHaveText(/^−zł\s42\.5$/)
  await page.keyboard.press('Backspace')
  await page.keyboard.press('Backspace')
  await expect(amount).toHaveText(/^−zł\s42$/)
  await page.keyboard.type('.75.')
  await expect(amount).toHaveText(/^−zł\s42\.75$/)
})

test('the date label follows the calendar past midnight', async ({ page }) => {
  await page.clock.install({ time: new Date('2030-06-15T23:59:00') })
  await page.goto('/transactions/new')
  await expect(page.getByRole('button', { name: 'Date: Today' })).toBeVisible()
  await page.clock.runFor('02:00')
  await expect(page.getByRole('button', { name: 'Date: Yesterday' })).toBeVisible()
})

test('shows a server error under the date when the date is too far ahead', async ({ page }) => {
  await page.clock.install({ time: new Date('2030-06-15T10:00:00') })
  await page.goto('/transactions/new')
  await page.getByRole('button', { name: 'Kawiarnie' }).click()
  await page.keyboard.type('5')
  await expect(page.getByLabel('Amount')).toHaveText(/^−zł\s5$/)
  await page.clock.setSystemTime(new Date('2029-06-01T10:00:00'))
  await page.getByRole('button', { name: 'Save' }).click()
  const dateButton = page.getByRole('button', { name: 'Date: Today' })
  await expect(page.getByText('The date can be at most one year ahead.')).toBeVisible()
  await expect(dateButton).toHaveAttribute('aria-invalid', 'true')
  await expect(dateButton).toHaveAccessibleDescription('The date can be at most one year ahead.')
  await expect(page).toHaveURL('/transactions/new')
})

test('shows tag chips on cards and filters by tag in the drawer', async ({ page }) => {
  await page.goto('/transactions')
  await showAllTime(page)
  await page.getByRole('searchbox', { name: 'Search' }).fill('Booking')
  const card = list(page).getByRole('listitem').filter({ hasText: 'Booking.com — hotel Barcelona' })
  await expect(card.getByRole('list', { name: 'Tags' })).toContainText('barcelona')
  await page.getByRole('searchbox', { name: 'Search' }).fill('')
  await page.getByRole('button', { name: 'Filters' }).click()
  const drawer = page.getByRole('dialog', { name: 'Filters' })
  await drawer.getByRole('combobox', { name: 'Tags' }).fill('barc')
  await pickOverlayOption(page, 'barcelona')
  await expect(drawer.getByRole('button', { name: 'Remove tag barcelona', exact: true })).toBeVisible()
  await drawer.getByRole('button', { name: 'Show results' }).click()
  await expect(drawer).toBeHidden()
  await expect(list(page).getByRole('listitem').filter({ hasText: 'Booking.com — hotel Barcelona' })).toHaveCount(1)
  await expect(page.getByRole('region', { name: 'Filter summary' })).toContainText('Found: 1 transaction')
})

test('scrolling over tag suggestions keeps the page behind the drawer still', async ({ page }) => {
  await page.goto('/transactions')
  await showAllTime(page)
  await page.getByRole('button', { name: 'Filters' }).click()
  const drawer = page.getByRole('dialog', { name: 'Filters' })
  await drawer.getByRole('combobox', { name: 'Tags' }).fill('barc')
  const suggestion = overlayOption(page, 'barcelona')
  await expect(suggestion).toBeVisible()
  const box = await suggestion.boundingBox()
  await page.mouse.move((box?.x ?? 0) + 20, (box?.y ?? 0) + 10)
  await page.mouse.wheel(0, 150)
  await pickOverlayOption(page, 'barcelona')
  await expect(drawer.getByRole('button', { name: 'Remove tag barcelona', exact: true })).toBeVisible()
  expect(await page.evaluate(() => window.scrollY)).toBe(0)
})
